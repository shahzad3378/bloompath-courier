import Link from "next/link";
import { Download, FileSpreadsheet, Globe2 } from "lucide-react";
import { ShipmentDateFields } from "@/components/shipment-date-fields";
import { requireProfile } from "@/lib/auth";
import { internalRoles } from "@/lib/roles";
import { createClient } from "@/lib/supabase/server";

export const metadata = { title: "Canada Customs Report" };

export default async function CanadaCustomsClearancePage({ searchParams }: {
  searchParams: Promise<{ from?: string; to?: string }>;
}) {
  const profile = await requireProfile([...internalRoles, "shipper"]);
  const params = await searchParams;
  const valid = (value?: string) => {
    if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return "";
    const date = new Date(`${value}T00:00:00Z`);
    return Number.isNaN(date.valueOf()) || date.toISOString().slice(0, 10) !== value ? "" : value;
  };
  const from = valid(params.from);
  const to = valid(params.to);
  const supabase = await createClient();
  let query = supabase.from("shipments").select("id", { count: "exact", head: true })
    .eq("organization_id", profile.organization_id)
    .is("deleted_at", null)
    .eq("consignee_country_code", "CA")
    .neq("sender_country_code", "CA");
  if (profile.role === "shipper") query = query.eq("shipper_id", profile.id);
  if (from) query = query.gte("created_at", `${from}T00:00:00+04:00`);
  if (to) query = query.lte("created_at", `${to}T23:59:59.999+04:00`);
  const { count, error } = await query;

  const exportParams = new URLSearchParams();
  if (from) exportParams.set("from", from);
  if (to) exportParams.set("to", to);
  const csvHref = `/shipments/customs-clearance/export?${new URLSearchParams([...exportParams, ["format", "csv"]]).toString()}`;
  const xlsxHref = `/shipments/customs-clearance/export?${exportParams.toString()}`;

  return <div className="mx-auto max-w-[1500px]">
    <header className="flex flex-wrap items-end justify-between gap-4">
      <div><p className="text-sm font-semibold text-[#188459]">International shipments · Canada</p><h1 className="mt-1 text-3xl font-bold tracking-[-0.035em] text-[#17231e]">Customs clearance report</h1><p className="mt-2 max-w-2xl text-sm text-[#74827b]">Download the Canadian customs manifest in the supplied 34-column format. AWBs are generated by this system; shipment details come from the customer upload.</p></div>
      <div className="flex flex-wrap gap-2">
        <a href={csvHref} className="inline-flex h-11 items-center gap-2 rounded-xl border border-[#bdd9ca] bg-white px-4 text-sm font-bold text-[#13734b] shadow-sm"><Download className="size-4" />CSV</a>
        <a href={xlsxHref} className="inline-flex h-11 items-center gap-2 rounded-xl bg-[#13734b] px-4 text-sm font-bold text-white shadow-sm"><FileSpreadsheet className="size-4" />Excel</a>
      </div>
    </header>

    <nav aria-label="Shipment views" className="mt-6 flex w-fit max-w-full gap-1 overflow-x-auto rounded-xl border border-[#e0e8e4] bg-white p-1">
      <Link href="/shipments" className="whitespace-nowrap rounded-lg px-4 py-2.5 text-sm font-semibold text-[#617068] hover:bg-[#f4f8f6]">All Shipments</Link>
      <Link href="/shipments/customs-clearance" aria-current="page" className="whitespace-nowrap rounded-lg bg-[#e7f4ed] px-4 py-2.5 text-sm font-bold text-[#13734b]">Canada Customs</Link>
    </nav>

    <section className="mt-5 grid gap-4 lg:grid-cols-[minmax(0,1fr)_auto]">
      <form noValidate className="grid gap-3 rounded-2xl border border-[#e0e8e4] bg-white p-4 shadow-[0_8px_30px_rgba(24,51,39,0.045)] sm:grid-cols-2 xl:grid-cols-4">
        <div className="grid gap-3 sm:col-span-2 sm:grid-cols-3 xl:col-span-3"><ShipmentDateFields initialFrom={from} initialTo={to} /></div>
        <button className="h-11 self-end rounded-xl bg-[#e7f4ed] px-5 text-sm font-bold text-[#13734b]">Apply date filter</button>
      </form>
      <div className="flex items-center gap-3 rounded-2xl border border-[#d9e7df] bg-[#f2f8f4] px-5 py-4">
        <span className="grid size-10 shrink-0 place-items-center rounded-xl bg-white text-[#13734b]"><Globe2 className="size-5" /></span>
        <div><p className="text-2xl font-black tabular-nums text-[#17231e]">{error ? "—" : (count ?? 0).toLocaleString("en")}</p><p className="text-xs font-semibold text-[#617068]">Canada-bound international AWBs</p></div>
      </div>
    </section>

    {error ? <p role="alert" className="mt-4 rounded-xl border border-[#efcccc] bg-white p-4 text-sm font-semibold text-[#a13f3f]">Report count could not be loaded. Refresh and try again.</p> : null}
    <section className="mt-5 rounded-2xl border border-[#e0e8e4] bg-white p-5 text-sm leading-6 text-[#617068] shadow-[0_8px_30px_rgba(24,51,39,0.045)]">
      <h2 className="font-bold text-[#26372f]">Report fields</h2>
      <p className="mt-1">The exported columns and order match the attached customs file. Consignment, barcode and internal account number use the generated AWB; reference and customer-entered shipment details follow each uploaded shipment.</p>
      <p className="mt-2">For future international uploads, use the customs columns for Consignee Email, Incoterm, Item Quantity, Item Value and Country Of Origin. Item quantity defaults to one per AWB; a missing item value defaults to CAD 1 per parcel kg. These defaults also apply to older shipments when the report is downloaded.</p>
    </section>
  </div>;
}
