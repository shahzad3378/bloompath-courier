-- BloomPath Courier SaaS Core
-- Platform administration, plans, subscriptions and tenant usage limits.

create type public.subscription_status as enum (
  'trial',
  'active',
  'past_due',
  'suspended',
  'cancelled'
);

create type public.billing_cycle as enum (
  'monthly',
  'annual',
  'custom'
);

-- BloomPath platform owners/operators.
-- This is intentionally separate from profiles.role = 'super_admin',
-- because that role remains organization-scoped.
create table public.platform_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Commercial SaaS plans.
create table public.saas_plans (
  id bigint generated by default as identity primary key,
  code text not null unique
    check (code ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null
    check (char_length(name) between 2 and 80),
  description text,

  monthly_price numeric(12,2) not null default 0
    check (monthly_price >= 0),
  annual_price numeric(12,2) not null default 0
    check (annual_price >= 0),
  currency text not null default 'AED'
    check (char_length(currency) = 3),

  max_internal_users integer
    check (max_internal_users is null or max_internal_users >= 1),
  max_drivers integer
    check (max_drivers is null or max_drivers >= 1),
  max_shippers integer
    check (max_shippers is null or max_shippers >= 1),
  max_awbs_per_month integer
    check (max_awbs_per_month is null or max_awbs_per_month >= 1),

  custom_reports_enabled boolean not null default false,
  live_map_enabled boolean not null default false,
  finance_enabled boolean not null default true,
  api_enabled boolean not null default false,
  white_label_enabled boolean not null default false,
  custom_domain_enabled boolean not null default false,

  is_active boolean not null default true,
  display_order integer not null default 100,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One current SaaS subscription per courier organization.
create table public.organization_subscriptions (
  id bigint generated by default as identity primary key,

  organization_id uuid not null unique
    references public.organizations(id) on delete cascade,

  plan_id bigint not null
    references public.saas_plans(id) on delete restrict,

  status public.subscription_status not null default 'trial',
  billing_cycle public.billing_cycle not null default 'monthly',

  trial_starts_at timestamptz,
  trial_ends_at timestamptz,

  current_period_starts_at timestamptz,
  current_period_ends_at timestamptz,
  next_billing_at timestamptz,

  price_override numeric(12,2)
    check (price_override is null or price_override >= 0),

  currency text not null default 'AED'
    check (char_length(currency) = 3),

  auto_renew boolean not null default true,
  suspended_at timestamptz,
  cancelled_at timestamptz,

  notes text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint subscription_trial_dates_valid check (
    trial_ends_at is null
    or trial_starts_at is null
    or trial_ends_at >= trial_starts_at
  ),

  constraint subscription_period_dates_valid check (
    current_period_ends_at is null
    or current_period_starts_at is null
    or current_period_ends_at >= current_period_starts_at
  )
);

create index organization_subscriptions_status_idx
  on public.organization_subscriptions(status);

create index organization_subscriptions_plan_idx
  on public.organization_subscriptions(plan_id);

create index organization_subscriptions_next_billing_idx
  on public.organization_subscriptions(next_billing_at);

-- Monthly usage snapshots.
create table public.organization_usage_monthly (
  id bigint generated by default as identity primary key,

  organization_id uuid not null
    references public.organizations(id) on delete cascade,

  usage_month date not null,

  awb_count integer not null default 0 check (awb_count >= 0),
  internal_user_count integer not null default 0 check (internal_user_count >= 0),
  driver_count integer not null default 0 check (driver_count >= 0),
  shipper_count integer not null default 0 check (shipper_count >= 0),

  updated_at timestamptz not null default now(),

  unique (organization_id, usage_month)
);

-- Platform admin helper.
create or replace function private.is_platform_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.platform_admins pa
    where pa.user_id = (select auth.uid())
      and pa.is_active
  );
$$;

revoke all on function private.is_platform_admin() from public;
grant execute on function private.is_platform_admin() to authenticated;

-- RLS
alter table public.platform_admins enable row level security;
alter table public.saas_plans enable row level security;
alter table public.organization_subscriptions enable row level security;
alter table public.organization_usage_monthly enable row level security;

revoke all on public.platform_admins from anon;
revoke all on public.saas_plans from anon;
revoke all on public.organization_subscriptions from anon;
revoke all on public.organization_usage_monthly from anon;

grant select on public.saas_plans to authenticated;
grant select on public.organization_subscriptions to authenticated;
grant select on public.organization_usage_monthly to authenticated;

-- Platform admins can read their platform-admin membership.
create policy "platform admins can read platform admin records"
on public.platform_admins
for select
to authenticated
using ((select private.is_platform_admin()));

-- Active plans are visible to authenticated users.
create policy "authenticated users can read active plans"
on public.saas_plans
for select
to authenticated
using (is_active or (select private.is_platform_admin()));

-- Tenant users can see their own subscription.
-- Platform admins can see every subscription.
create policy "users can read permitted subscriptions"
on public.organization_subscriptions
for select
to authenticated
using (
  organization_id = (select private.current_organization_id())
  or (select private.is_platform_admin())
);

-- Tenant users can see their own usage.
-- Platform admins can see every tenant's usage.
create policy "users can read permitted usage"
on public.organization_usage_monthly
for select
to authenticated
using (
  organization_id = (select private.current_organization_id())
  or (select private.is_platform_admin())
);

-- Existing updated_at helper.
