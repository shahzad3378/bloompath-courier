-- Preserve all organizations that already exist before SaaS conversion.
-- They receive Enterprise access and remain active.
insert into public.organization_subscriptions (
  organization_id,
  plan_id,
  status,
  billing_cycle,
  current_period_starts_at,
  currency,
  auto_renew,
  notes
)
select
  o.id,
  p.id,
  'active'::public.subscription_status,
  'custom'::public.billing_cycle,
  now(),
  'AED',
  true,
  'Existing organization migrated to BloomPath Courier SaaS.'
from public.organizations o
cross join public.saas_plans p
where p.code = 'enterprise'
on conflict (organization_id) do nothing;
