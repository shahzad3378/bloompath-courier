-- CourierOS / BloomPath Courier
-- Third-party carrier operations.
--
-- Privacy rule:
-- Shippers only see the courier company's own AWB and generic shipment status.
-- 3PL partner name, partner AWB and internal notes live in separate internal tables.

-- ============================================================
-- 1. 3PL PARTNERS
-- ============================================================

create table if not exists public.third_party_carriers (
  id uuid primary key default gen_random_uuid(),

  organization_id uuid not null
    references public.organizations(id)
    on delete cascade,

  name text not null,
  code text not null,

  contact_name text,
  contact_phone text,
  contact_email text,

  integration_mode text not null default 'manual'
    check (integration_mode in ('manual', 'bulk', 'api')),

  is_active boolean not null default true,

  created_by uuid references public.profiles(id),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint third_party_carriers_name_length
    check (char_length(name) between 2 and 120),

  constraint third_party_carriers_code_length
    check (char_length(code) between 2 and 30),

  constraint third_party_carriers_org_code_unique
    unique (organization_id, code)
);


-- ============================================================
-- 2. SHIPMENT DELIVERY MODE
-- ============================================================
-- Safe for shipper to know:
-- own_fleet / third_party
--
-- We DO NOT store partner tracking number here.

alter table public.shipments
  add column if not exists fulfillment_mode text
  not null default 'own_fleet'
  check (
    fulfillment_mode in (
      'own_fleet',
      'third_party'
    )
  );


-- ============================================================
-- 3. INTERNAL 3PL SHIPMENT LINK
-- ============================================================
-- IMPORTANT:
-- This table contains confidential carrier-side information.
-- Shippers will NOT get SELECT permission through RLS.

create table if not exists public.third_party_shipment_links (
  id bigint generated by default as identity primary key,

  organization_id uuid not null
    references public.organizations(id)
    on delete cascade,

  shipment_id bigint not null
    references public.shipments(id)
    on delete cascade,

  carrier_id uuid not null
    references public.third_party_carriers(id),

  partner_tracking_number text,

  partner_status text,

  handed_over_at timestamptz,
  last_status_at timestamptz,

  return_reason text,

  internal_notes text,

  created_by uuid references public.profiles(id),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint third_party_shipment_links_shipment_unique
    unique (shipment_id),

  constraint third_party_partner_awb_length
    check (
      partner_tracking_number is null
      or char_length(partner_tracking_number) between 2 and 100
    ),

  constraint third_party_internal_notes_length
    check (
      internal_notes is null
      or char_length(internal_notes) <= 1000
    )
);


create unique index if not exists third_party_partner_awb_unique
on public.third_party_shipment_links (
  organization_id,
  carrier_id,
  partner_tracking_number
)
where partner_tracking_number is not null;


create index if not exists third_party_links_carrier_idx
on public.third_party_shipment_links (
  carrier_id,
  updated_at desc
);


-- ============================================================
-- 4. INTERNAL 3PL STATUS HISTORY
-- ============================================================

create table if not exists public.third_party_status_updates (
  id bigint generated by default as identity primary key,

  organization_id uuid not null
    references public.organizations(id)
    on delete cascade,

  shipment_id bigint not null
    references public.shipments(id)
    on delete cascade,

  carrier_id uuid not null
    references public.third_party_carriers(id),

  status text not null
    check (
      status in (
        'handed_over',
        'in_transit',
        'delivered',
        'undelivered',
        'return_initiated',
        'return_in_transit',
        'returned_to_warehouse',
        'returned_to_shipper'
      )
    ),

  attempt_number smallint
    check (
      attempt_number is null
      or attempt_number between 1 and 3
    ),

  undelivered_reason text,

  return_reason text,

  internal_notes text,

  proof_path text,

  source text not null default 'manual'
    check (
      source in (
        'manual',
        'bulk',
        'api'
      )
    ),

  updated_by uuid references public.profiles(id),

  created_at timestamptz not null default now(),

  constraint third_party_status_notes_length
    check (
      internal_notes is null
      or char_length(internal_notes) <= 1000
    )
);


create index if not exists third_party_status_shipment_idx
on public.third_party_status_updates (
  shipment_id,
  created_at desc,
  id desc
);


-- ============================================================
-- 5. INTERNAL STATUS GUARD + SHIPMENT SYNC
-- ============================================================

create or replace function private.guard_third_party_status_update()
returns trigger
language plpgsql
security definer
set search_path = public, private
as $$
declare
  shipment_record public.shipments%rowtype;
  link_record public.third_party_shipment_links%rowtype;
  next_attempt smallint;
  immediate_return boolean := false;
begin

  select *
  into shipment_record
  from public.shipments
  where id = new.shipment_id
    and organization_id = new.organization_id
    and deleted_at is null
  for update;

  if not found then
    raise exception 'Shipment not found.';
  end if;


  if shipment_record.fulfillment_mode <> 'third_party' then
    raise exception 'Shipment is not assigned to a third-party carrier.';
  end if;


  select *
  into link_record
  from public.third_party_shipment_links
  where shipment_id = shipment_record.id
    and organization_id = shipment_record.organization_id;

  if not found then
    raise exception '3PL shipment link was not found.';
  end if;


  if link_record.carrier_id <> new.carrier_id then
    raise exception '3PL carrier does not match this shipment.';
  end if;


  new.organization_id := shipment_record.organization_id;
  new.updated_by := coalesce(new.updated_by, auth.uid());


  -- ========================================================
  -- HANDED OVER
  -- ========================================================

  if new.status = 'handed_over' then

    update public.third_party_shipment_links
    set
      partner_status = 'handed_over',
      handed_over_at = coalesce(handed_over_at, now()),
      last_status_at = now(),
      internal_notes = new.internal_notes,
      updated_at = now()
    where shipment_id = shipment_record.id;

    update public.shipments
    set
      status = 'out_for_delivery'::public.shipment_status,
      assigned_driver_id = null
    where id = shipment_record.id;

    return new;
  end if;


  -- ========================================================
  -- IN TRANSIT
  -- ========================================================

  if new.status = 'in_transit' then

    update public.third_party_shipment_links
    set
      partner_status = 'in_transit',
      last_status_at = now(),
      internal_notes = new.internal_notes,
      updated_at = now()
    where shipment_id = shipment_record.id;

    update public.shipments
    set
      status = 'out_for_delivery'::public.shipment_status,
      assigned_driver_id = null
    where id = shipment_record.id;

    return new;
  end if;


  -- ========================================================
  -- DELIVERED
  -- ========================================================

  if new.status = 'delivered' then

    next_attempt :=
      coalesce(
        new.attempt_number,
        case
          when shipment_record.delivery_attempt_count = 0
          then 1
          else shipment_record.delivery_attempt_count
        end
      );

    update public.third_party_shipment_links
    set
      partner_status = 'delivered',
      last_status_at = now(),
      internal_notes = new.internal_notes,
      updated_at = now()
    where shipment_id = shipment_record.id;

    update public.shipments
    set
      status = 'delivered'::public.shipment_status,
      delivered_at = now(),

      delivery_attempt_count =
        greatest(
          delivery_attempt_count,
          next_attempt
        ),

      last_undelivered_reason = null,
      assigned_driver_id = null

    where id = shipment_record.id;

    return new;
  end if;


  -- ========================================================
  -- UNDELIVERED
  -- ========================================================

  if new.status = 'undelivered' then

    next_attempt :=
      coalesce(
        new.attempt_number,
        shipment_record.delivery_attempt_count + 1
      );


    if next_attempt < 1 or next_attempt > 3 then
      raise exception '3PL attempt number must be between 1 and 3.';
    end if;


    if next_attempt < shipment_record.delivery_attempt_count then
      raise exception 'Attempt number cannot be lower than current shipment attempt count.';
    end if;


    if new.undelivered_reason is null
      or new.undelivered_reason not in (

        'customer_unavailable',
        'customer_refused',
        'customer_cancelled',

        'wrong_address',
        'phone_unreachable',

        'reschedule_requested',
        'cash_not_ready',

        'restricted_access',
        'out_of_coverage',

        'address_closed',

        'no_response',

        'other'
      )
    then
      raise exception 'Select a valid undelivered reason.';
    end if;


    immediate_return :=
      new.undelivered_reason in (
        'customer_refused',
        'customer_cancelled'
      );


    update public.third_party_shipment_links
    set
      partner_status =
        case
          when immediate_return or next_attempt >= 3
          then 'return_initiated'
          else 'undelivered'
        end,

      last_status_at = now(),

      return_reason =
        case

          when new.undelivered_reason = 'customer_refused'
          then 'customer_refused'

          when new.undelivered_reason = 'customer_cancelled'
          then 'customer_cancelled'

          when next_attempt >= 3
          then 'attempts_exhausted'

          else return_reason

        end,

      internal_notes = new.internal_notes,
      updated_at = now()

    where shipment_id = shipment_record.id;


    update public.shipments
    set

      status =
        case

          when immediate_return
            or next_attempt >= 3

          then 'return_initiated'::public.shipment_status

          else 'undelivered'::public.shipment_status

        end,

      delivery_attempt_count = next_attempt,

      last_undelivered_reason =
        new.undelivered_reason,

      delivered_at = null,

      assigned_driver_id = null

    where id = shipment_record.id;


    return new;
  end if;


  -- ========================================================
  -- RETURN START
  -- ========================================================

  if new.status in (
    'return_initiated',
    'return_in_transit'
  ) then

    if new.return_reason is null
      or new.return_reason not in (

        'attempts_exhausted',
        'customer_cancelled',
        'customer_refused',

        'no_response',
        'wrong_address',

        'out_of_coverage',
        'damaged',

        'carrier_issue',
        'other'
      )
    then
      raise exception 'Select a valid return reason.';
    end if;


    update public.third_party_shipment_links
    set
      partner_status = new.status,

      return_reason = new.return_reason,

      last_status_at = now(),

      internal_notes = new.internal_notes,

      updated_at = now()

    where shipment_id = shipment_record.id;


    update public.shipments
    set
      status = 'return_initiated'::public.shipment_status,
      assigned_driver_id = null

    where id = shipment_record.id;


    return new;
  end if;


  -- ========================================================
  -- RETURNED TO OUR WAREHOUSE
  -- ========================================================

  if new.status = 'returned_to_warehouse' then

    if coalesce(
      new.return_reason,
      link_record.return_reason
    ) is null
    then
      raise exception 'Return reason is required.';
    end if;


    update public.third_party_shipment_links
    set

      partner_status = 'returned_to_warehouse',

      return_reason =
        coalesce(
          new.return_reason,
          return_reason
        ),

      last_status_at = now(),

      internal_notes = new.internal_notes,

      updated_at = now()

    where shipment_id = shipment_record.id;


    update public.shipments
    set
      status = 'return_initiated'::public.shipment_status,
      assigned_driver_id = null

    where id = shipment_record.id;


    return new;
  end if;


  -- ========================================================
  -- FINAL RETURN TO SHIPPER
  -- ========================================================

  if new.status = 'returned_to_shipper' then

    update public.third_party_shipment_links
    set

      partner_status = 'returned_to_shipper',

      return_reason =
        coalesce(
          new.return_reason,
          return_reason
        ),

      last_status_at = now(),

      internal_notes = new.internal_notes,

      updated_at = now()

    where shipment_id = shipment_record.id;


    update public.shipments
    set
      status = 'returned_to_shipper'::public.shipment_status,
      assigned_driver_id = null

    where id = shipment_record.id;


    return new;
  end if;


  return new;

end;
$$;


drop trigger if exists third_party_status_guard_insert
on public.third_party_status_updates;


create trigger third_party_status_guard_insert
before insert
on public.third_party_status_updates
for each row
execute function private.guard_third_party_status_update();


